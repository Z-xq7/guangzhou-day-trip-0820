function discoveryPhoto(
  index: number,
  slug: string,
  alt: string,
  caption: string,
  isRepresentativeOnly = false,
): LicensedDiscoveryPhoto {
  const credit = photoCredits[index];
  return {
    src: `images/discovery/${String(index).padStart(2, "0")}-${slug}.webp`,
    alt,
    caption,
    ...credit,
    modifications: MODIFICATIONS,
    ...(isRepresentativeOnly ? { isRepresentativeOnly: true } : {}),
  };
}

